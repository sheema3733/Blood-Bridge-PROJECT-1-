export function calculateDispatchScore(record: GreenCorridorCoordinationRecord): number {
  let score = 100;
  if (record.urgencyTier === 'CODE_RED_CRITICAL') score += 50;
  if (record.actualTransitTimeMinutes <= record.estimatedTransitTimeMinutes) score += 20;
  if (record.thermalExcursionDetected) score -= 80;
  return score;
}

export function isDispatchSlaMet(record: GreenCorridorCoordinationRecord): boolean {
  return record.actualTransitTimeMinutes <= record.estimatedTransitTimeMinutes + 5;
}
