export function getHemovigilanceProtocolById(id: string): HemovigilanceProtocol | undefined {
  return HEMOVIGILANCEREPORTING_REGISTRY.find(item => item.id === id);
}

export function filterHemovigilanceProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): HemovigilanceProtocol[] {
  return HEMOVIGILANCEREPORTING_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateHemovigilanceProtocolCompatibility(protocol: HemovigilanceProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
