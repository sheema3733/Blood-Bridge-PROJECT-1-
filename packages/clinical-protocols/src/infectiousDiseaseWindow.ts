export function getTTIWindowProtocolById(id: string): TTIWindowProtocol | undefined {
  return INFECTIOUSDISEASEWINDOW_REGISTRY.find(item => item.id === id);
}

export function filterTTIWindowProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): TTIWindowProtocol[] {
  return INFECTIOUSDISEASEWINDOW_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateTTIWindowProtocolCompatibility(protocol: TTIWindowProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
