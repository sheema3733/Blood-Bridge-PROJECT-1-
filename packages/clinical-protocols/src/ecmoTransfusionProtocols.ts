export function getECMOTransfusionProtocolById(id: string): ECMOTransfusionProtocol | undefined {
  return ECMOTRANSFUSIONPROTOCOLS_REGISTRY.find(item => item.id === id);
}

export function filterECMOTransfusionProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): ECMOTransfusionProtocol[] {
  return ECMOTRANSFUSIONPROTOCOLS_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateECMOTransfusionProtocolCompatibility(protocol: ECMOTransfusionProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
