export function getLiverTransplantProtocolById(id: string): LiverTransplantProtocol | undefined {
  return LIVERTRANSPLANTTRANSFUSION_REGISTRY.find(item => item.id === id);
}

export function filterLiverTransplantProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): LiverTransplantProtocol[] {
  return LIVERTRANSPLANTTRANSFUSION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateLiverTransplantProtocolCompatibility(protocol: LiverTransplantProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
