export function getPTPProtocolById(id: string): PTPProtocol | undefined {
  return PTPMANAGEMENT_REGISTRY.find(item => item.id === id);
}

export function filterPTPProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): PTPProtocol[] {
  return PTPMANAGEMENT_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validatePTPProtocolCompatibility(protocol: PTPProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
