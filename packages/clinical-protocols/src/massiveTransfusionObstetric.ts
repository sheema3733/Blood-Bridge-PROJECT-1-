export function getMTPOpstetricProtocolById(id: string): MTPOpstetricProtocol | undefined {
  return MASSIVETRANSFUSIONOBSTETRIC_REGISTRY.find(item => item.id === id);
}

export function filterMTPOpstetricProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): MTPOpstetricProtocol[] {
  return MASSIVETRANSFUSIONOBSTETRIC_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateMTPOpstetricProtocolCompatibility(protocol: MTPOpstetricProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
