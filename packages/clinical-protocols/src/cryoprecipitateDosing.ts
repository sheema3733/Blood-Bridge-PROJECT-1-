export function getCryoprecipitateProtocolById(id: string): CryoprecipitateProtocol | undefined {
  return CRYOPRECIPITATEDOSING_REGISTRY.find(item => item.id === id);
}

export function filterCryoprecipitateProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): CryoprecipitateProtocol[] {
  return CRYOPRECIPITATEDOSING_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateCryoprecipitateProtocolCompatibility(protocol: CryoprecipitateProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
