export function getNeurosurgeryProtocolById(id: string): NeurosurgeryProtocol | undefined {
  return NEUROSURGERYTRANSFUSION_REGISTRY.find(item => item.id === id);
}

export function filterNeurosurgeryProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): NeurosurgeryProtocol[] {
  return NEUROSURGERYTRANSFUSION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateNeurosurgeryProtocolCompatibility(protocol: NeurosurgeryProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
