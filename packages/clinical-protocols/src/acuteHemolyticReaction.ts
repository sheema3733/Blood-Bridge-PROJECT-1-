export function getAHTRProtocolById(id: string): AHTRProtocol | undefined {
  return ACUTEHEMOLYTICREACTION_REGISTRY.find(item => item.id === id);
}

export function filterAHTRProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): AHTRProtocol[] {
  return ACUTEHEMOLYTICREACTION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateAHTRProtocolCompatibility(protocol: AHTRProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
