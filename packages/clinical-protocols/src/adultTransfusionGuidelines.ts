export function getAdultTransfusionProtocolById(id: string): AdultTransfusionProtocol | undefined {
  return ADULTTRANSFUSIONGUIDELINES_REGISTRY.find(item => item.id === id);
}

export function filterAdultTransfusionProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): AdultTransfusionProtocol[] {
  return ADULTTRANSFUSIONGUIDELINES_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateAdultTransfusionProtocolCompatibility(protocol: AdultTransfusionProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
