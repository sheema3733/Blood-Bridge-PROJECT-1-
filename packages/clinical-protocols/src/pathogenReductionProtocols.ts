export function getPathogenReductionProtocolById(id: string): PathogenReductionProtocol | undefined {
  return PATHOGENREDUCTIONPROTOCOLS_REGISTRY.find(item => item.id === id);
}

export function filterPathogenReductionProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): PathogenReductionProtocol[] {
  return PATHOGENREDUCTIONPROTOCOLS_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validatePathogenReductionProtocolCompatibility(protocol: PathogenReductionProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
