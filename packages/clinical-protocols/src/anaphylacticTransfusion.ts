export function getAnaphylaxisProtocolById(id: string): AnaphylaxisProtocol | undefined {
  return ANAPHYLACTICTRANSFUSION_REGISTRY.find(item => item.id === id);
}

export function filterAnaphylaxisProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): AnaphylaxisProtocol[] {
  return ANAPHYLACTICTRANSFUSION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateAnaphylaxisProtocolCompatibility(protocol: AnaphylaxisProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
