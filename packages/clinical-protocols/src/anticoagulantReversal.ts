export function getDOACReversalProtocolById(id: string): DOACReversalProtocol | undefined {
  return ANTICOAGULANTREVERSAL_REGISTRY.find(item => item.id === id);
}

export function filterDOACReversalProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): DOACReversalProtocol[] {
  return ANTICOAGULANTREVERSAL_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateDOACReversalProtocolCompatibility(protocol: DOACReversalProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
