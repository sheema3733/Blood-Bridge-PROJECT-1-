export function getFNHTRProtocolById(id: string): FNHTRProtocol | undefined {
  return FEBRILENONHEMOLYTIC_REGISTRY.find(item => item.id === id);
}

export function filterFNHTRProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): FNHTRProtocol[] {
  return FEBRILENONHEMOLYTIC_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateFNHTRProtocolCompatibility(protocol: FNHTRProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
