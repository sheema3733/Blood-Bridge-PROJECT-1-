export function getAutologousProtocolById(id: string): AutologousProtocol | undefined {
  return AUTOLOGOUSBLOODTRANSFUSION_REGISTRY.find(item => item.id === id);
}

export function filterAutologousProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): AutologousProtocol[] {
  return AUTOLOGOUSBLOODTRANSFUSION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateAutologousProtocolCompatibility(protocol: AutologousProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
