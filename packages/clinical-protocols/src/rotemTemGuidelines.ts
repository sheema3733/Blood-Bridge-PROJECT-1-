export function getROTEMProtocolById(id: string): ROTEMProtocol | undefined {
  return ROTEMTEMGUIDELINES_REGISTRY.find(item => item.id === id);
}

export function filterROTEMProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): ROTEMProtocol[] {
  return ROTEMTEMGUIDELINES_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateROTEMProtocolCompatibility(protocol: ROTEMProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
