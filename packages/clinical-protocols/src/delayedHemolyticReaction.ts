export function getDHTRProtocolById(id: string): DHTRProtocol | undefined {
  return DELAYEDHEMOLYTICREACTION_REGISTRY.find(item => item.id === id);
}

export function filterDHTRProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): DHTRProtocol[] {
  return DELAYEDHEMOLYTICREACTION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateDHTRProtocolCompatibility(protocol: DHTRProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
