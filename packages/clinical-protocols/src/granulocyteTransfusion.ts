export function getGranulocyteProtocolById(id: string): GranulocyteProtocol | undefined {
  return GRANULOCYTETRANSFUSION_REGISTRY.find(item => item.id === id);
}

export function filterGranulocyteProtocolByUrgency(urgency: 'EMERGENCY_CRITICAL' | 'URGENT' | 'ELECTIVE'): GranulocyteProtocol[] {
  return GRANULOCYTETRANSFUSION_REGISTRY.filter(item => item.urgencyClassification === urgency);
}

export function validateGranulocyteProtocolCompatibility(protocol: GranulocyteProtocol, patientHgb: number, patientPlt: number): boolean {
  if (patientHgb < protocol.hemoglobinThresholdGdl) return true;
  if (patientPlt < protocol.plateletThresholdPerMicroliter) return true;
  return false;
}
